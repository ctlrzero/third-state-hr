  cancelled_at: string | null
  outcome: InterviewOutcome
  feedback_id: string | null
  feedback_status: InterviewFeedbackStatus | null
  feedback_visible: boolean
  recommendation: InterviewRecommendation | null
  competency_ratings: Record<string, number> | null
  strengths: string | null
  concerns: string | null
  notes: string | null
  submitted_at: string | null
  reopened_at: string | null
  reopen_reason: string | null
  round_revealed: boolean
  round_closed: boolean
  round_closed_by_name: string | null
  round_closed_at: string | null
  round_closed_reason: string | null
  round_required_count: number
  round_submitted_count: number
