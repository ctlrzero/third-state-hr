// Row shape returned by get_application_interview_feedback() — the Recruiting
// module's reveal-gated replacement for a raw interviews/interview_feedback
// join (Phase 3.12). A "round" is every non-cancelled interview sharing the
// same (application_id, stage_id). For owner/entity_admin, feedback_visible
// is always true and every content field reflects the real row (or null if
// no feedback was ever saved). For location_manager, feedback_visible is
// only true once the round is revealed (every required interviewer submitted,
// or a Recruiting Admin/Owner closed the round) AND this specific row's own
// status is 'submitted' — a reopened row drops back out of view immediately.
// When feedback_visible is false, every content field below is null server-
// side; the client never receives it to redact.
